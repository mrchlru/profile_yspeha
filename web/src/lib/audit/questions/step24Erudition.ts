/**
 * Возвращает индекс первого вопроса без выбранного варианта или `questions.length`,
 * если ответы получены на все вопросы (это нормально — таймер всё равно главенствует).
 */
export function getNextUnansweredStep24Index(
  questions: ReadonlyArray<AuditStep24Question>,
  answers: Readonly<Record<string, string | null>>
): number {
  for (let i = 0; i < questions.length; i += 1) {
    const q = questions[i];
    if (q === undefined) {
      continue;
    }
    const key = `q${String(q.index)}`;
    const v = answers[key];
    if (v === null || v === undefined || v === "") {
      return i;
    }
  }
  return questions.length;
}
