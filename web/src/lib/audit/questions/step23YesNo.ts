/**
 * Шаг 23 аудита — коммуникативные и организаторские склонности (КОС-1).
 * Формат, видимый пользователю: 40 утверждений с ответом «да / нет».
 * На шаг даётся 18 минут (живой таймер с автопереходом).
 *
 * Источник: `screen-research-audit/тесты и ключи к ним/Тест 16.docx` —
 * материалы заказчика, тексты перенесены без изменения смысла; нормализованы
 * кавычки и точечно поправлены технические опечатки исходника (`чувстве`
 * → `чувство`, `иди` → `или` и т. п.). Официальное название методики
 * пользователю не показывается.
 *
 * По ключу: нечётные пункты (1, 3, 5, …) относятся к шкале коммуникативных
 * склонностей, чётные (2, 4, 6, …) — к шкале организаторских. Поле `track`
 * заполнено для будущего PR с расчётом баллов и итогового заключения;
 * пользователь его не видит.
 */

export type AuditStep23Question = {
  /** Сквозной номер 1..40, используется как часть ключа ответа `q<N>`. */
  index: number;
  text: string;
  /**
   * Шкала: `comm` — коммуникативные склонности, `org` — организаторские.
   * Не отображается в UI; используется только для расчёта ключа.
   */
  track: "comm" | "org";
};

function _q(
  index: number,
  text: string
): AuditStep23Question {
  const track: "comm" | "org" = index % 2 === 1 ? "comm" : "org";
  return { index, text, track };
}

