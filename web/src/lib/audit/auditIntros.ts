/** Возвращает завершающее предложение «На выполнение этого теста даётся ровно X минут(ы)». */
function _cfitTimerLine(minutes: number): string {
  const word = minutes === 1 ? "минута" : minutes < 5 ? "минуты" : "минут";
  return `На выполнение этого теста даётся ровно ${String(minutes)} ${word}. ${TIMER_TAIL}`;
}

