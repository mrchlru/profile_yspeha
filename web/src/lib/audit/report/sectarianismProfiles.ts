/** Возвращает описание профиля по идентификатору. */
export function getSectarianismProfileDescription(
  id: SectarianismProfileId
): SectarianismProfileDescription | null {
  return SECTARIANISM_PROFILE_DESCRIPTIONS.find((item) => item.id === id) ?? null;
}

/** Собирает полный текст характеристики для HR-отчёта. */
export function formatSectarianismProfileForHr(
  description: SectarianismProfileDescription,
  scorePercent: number
): string {
  return [
    description.heading,
    `Совпадение с ключом: ${String(Math.round(scorePercent))}%.`,
    `Наименование: ${description.nameLabel}`,
    `Характеристика: ${description.characteristic}`,
    `Особенности: ${description.features}`,
    `Причина экстремизма: ${description.extremismReason}`,
  ].join("\n\n");
}
