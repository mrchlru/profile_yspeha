export type PsychStateIndicatorKey = "pi" | "lo" | "pm" | "ipv" | "load";

export type PsychStateIndicatorPart = {
  key: PsychStateIndicatorKey;
  title: string;
  docBand: ManagerBriefDocBand | "low" | "normal" | "high" | "critical";
  referencePhrase: string;
};

const PSYCH_INDICATOR_TITLES: Readonly<Record<PsychStateIndicatorKey, string>> = {
  pi: "Эмоциональное истощение",
  lo: "Личностное отдаление",
  pm: "Профессиональная мотивация и удовлетворённость",
  ipv: "Интегральное психологическое состояние",
  load: "Уровень рабочей нагрузки",
};

/** Пять показателей психологического состояния отдельными фразами (без склейки). */
export function listPsychologicalStateIndicatorParts(input: {
  pi: ManagerBriefDocBand | null;
  lo: ManagerBriefDocBand | null;
  pm: ManagerBriefDocBand | null;
  ipv: ManagerBriefDocBand | null;
  load: keyof typeof PSYCH_LOAD | null;
}): ReadonlyArray<PsychStateIndicatorPart> {
  const parts: PsychStateIndicatorPart[] = [];
  if (input.pi !== null) {
    parts.push({
      key: "pi",
      title: PSYCH_INDICATOR_TITLES.pi,
      docBand: input.pi,
      referencePhrase: PSYCH_PI[input.pi],
    });
  }
  if (input.lo !== null) {
    parts.push({
      key: "lo",
      title: PSYCH_INDICATOR_TITLES.lo,
      docBand: input.lo,
      referencePhrase: PSYCH_LO[input.lo],
    });
  }
  if (input.pm !== null) {
    parts.push({
      key: "pm",
      title: PSYCH_INDICATOR_TITLES.pm,
      docBand: input.pm,
      referencePhrase: PSYCH_PM[input.pm],
    });
  }
  if (input.ipv !== null) {
    parts.push({
      key: "ipv",
      title: PSYCH_INDICATOR_TITLES.ipv,
      docBand: input.ipv,
      referencePhrase: PSYCH_IPV[input.ipv],
    });
  }
  if (input.load !== null) {
    parts.push({
      key: "load",
      title: PSYCH_INDICATOR_TITLES.load,
      docBand: input.load,
      referencePhrase: PSYCH_LOAD[input.load],
    });
  }
  return parts;
}

export function managerBriefPsychologicalStateText(parts: ReadonlyArray<string>): string {
  return parts.filter((p) => p.trim().length > 0).join(" ");
}

export function managerBriefPsychTexts(input: {
  pi: ManagerBriefDocBand | null;
  lo: ManagerBriefDocBand | null;
  pm: ManagerBriefDocBand | null;
  ipv: ManagerBriefDocBand | null;
  load: keyof typeof PSYCH_LOAD | null;
}): string {
  const chunks = listPsychologicalStateIndicatorParts(input).map((part) => part.referencePhrase);
  return managerBriefPsychologicalStateText(chunks);
}

export function motivationPairKey(
  first: GerchikovMotivationType,
  second: GerchikovMotivationType
): string {
  return `${GERCHIKOV_TYPE_SHORT_LABELS[first]}|${GERCHIKOV_TYPE_SHORT_LABELS[second]}`;
}

